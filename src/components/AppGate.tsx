//    **syncStore の hydrate が「サーバーが空ならローカルの内容を移行する」ので、
//    それまでに入れた冷蔵庫や買い物リストはそのまま引き継がれる**（新規アカウントの場合）。
//    既にデータのあるアカウントにログインした場合は、そのアカウント側のデータが正となる。
