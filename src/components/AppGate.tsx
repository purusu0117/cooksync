"use client";

// アカウントを作らなくてもアプリを使える。ログインは「端末間で同期したい人だけ」の任意機能。
//
// ⚠️ 以前はここで /mypage 以外を全部ブロックしていた（2026-08-01 の監査で発覚）。
//    初見のユーザーはタブを押しても全部ログイン画面に飛ばされ、**何ひとつ見られなかった**。
//    - App Store ガイドライン **5.1.1(v)**：アカウント機能が本質でないアプリは、
//      ログイン無しで使わせる必要がある。CookSyncの中核（食材を登録して献立を考える）は
//      端末ローカルだけで成立するので、登録必須は正当化しにくくリジェクト理由になる。
//    - 審査担当は開いた瞬間に登録を強制され、そこで詰まる。
//    - 普通のユーザーも「中身を見る前にメールアドレスを要求される」ので離脱する。
//
// データはどうなるか：
//    未ログインの間は端末ごとのUUID（cooksync:uid）配下に保存される。
//    あとで登録・ログインすると uid がアカウントの dataId に切り替わる。
//
//    ⚠️ ここには以前「サーバーが空ならローカルの内容を移行するので引き継がれる」と
//       書いてあったが、**それは事実ではなかった**（2026-08-01 の実測で確定）。
//       移行元が localStorage なのに、アプリのデータを localStorage に書く経路が
//       既に廃止されていたため、移行元は常に空。実際には
//         - 登録して**すぐ何か操作した**場合だけ、メモリが生きていて偶然引き継がれる
//         - 登録して**何もせず閉じた**場合は、匿名uid配下に取り残されて**完全に消える**
//         - ログイン（reloadする）は、アカウント側が空でも引き継がれず**空になる**
//       という挙動だった。
//
//    → いまは syncStore が引き継ぎを明示的に行う（setUid が印を残し、次の同期で移行）。
//      端末キャッシュを常に書き戻しているので、reload の有無に関わらず同じ結果になる。
//      引き継ぐのは「匿名のまま貯めた分」だけで、既にデータのあるアカウントに
//      ログインした場合は、そのアカウント側のデータが正となる。
//
// このコンポーネントは layout.tsx が包んでいるので、消さずに素通しにしてある。
// 将来「本当にアカウントが必要な画面」ができたら、ここに条件を足す。
export default function AppGate({ children }: { children: React.ReactNode }) {
  return <>{children}</>;
}
