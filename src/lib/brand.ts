export const APP_NAME = "CookSync";

/**
 * APP_TAGLINE ＝ **初見の人が読む場所**の文言。
 *
 * 出る場所：ホーム画面のロゴ下 / マイページ / PWA manifest の description /
 *          <title> の後半（＝App Store のサブタイトルに相当する一等地）。
 * つまり読むのは「CookSync を今日はじめて見た人」。ここでは製品の説明ではなく、
 * **その人がもう持っている悩み**を言い当てる（Preferences/copywriting-audience.md）。
 *
 * 旧「AIが勝手に、分量を変えない。」を差し替えた理由（2026-08-01・大翔の指摘）：
 *   「全然日本語の意味がわかんないっす。どういうことこれ？」
 *   根拠（競合CookGo 10万DL・レビュー9,015件の★1が「砂糖大さじ1→小さじ1」級の
 *   分量ミスに集中）は正しいが、**否定形は否定される対象を知らない人には空振りする**。
 *   初見の人は「AIが分量を勝手に変える」という現象自体を知らない。
 *   → 差別化は捨てず、比較検討層が読む場所（LPの中ほど＝APP_PROMISE／
 *     ストアの説明文本文）へ置き場所を下げた。
 *
 * 採用：「今日なに作るか、家にあるもので決まる。」（18字）
 *   ・夕食の悩み1位＝「献立を考えること」65.8%（レパートリー不足44.1%・後片付け40.8%を上回る）。
 *     その1位を、製品を知らなくても意味が通る言葉でそのまま書いた。
 *   ・肯定形。「決まる」で読後の状態（結果）まで言い切っている。
 *   ・Onboarding の見出し「今日なに作るか、まだ決まっていないなら」と同じ悩みで揃えた。
 *   ・「家にあるもの」は pecco（50万DL）がサブタイトルで占有する
 *     「冷蔵庫にあるもので最適な献立レシピを提案し賞味期限も管理」と語をずらすため。
 *     同じ「冷蔵庫にあるもので」を真正面から言うと劣化版に見える。
 *
 * 却下案：
 *   ・「冷蔵庫から、今日のひと皿。」…（旧々案）competitor と同じことしか言えていない。
 *   ・「冷蔵庫にあるもので、献立が決まる。」…pecco のサブタイトルとほぼ同文。
 *   ・「今日なに作るか、もう悩まない。」…否定形。悩みは既知なので空振りはしないが、
 *     「悩まない」は結果の言い換えでしかなく、どうやってかが1ミリも分からない。
 *   ・「帰り道で、今日の晩ごはんが決まる。」…献立を考えるのは「帰宅途中50.4%」という
 *     調査に一番忠実で刺さるが、**冷蔵庫アプリだと分からない**ので一等地には置けない。
 *     広告コピー・PR の見出し候補として温存。
 *   ・「今日なに作る？が5秒で決まる。」…5秒の根拠が無い。数字は実測できるまで書かない。
 *
 * 実装の裏付け（この文言が嘘にならない条件。壊れたら文言も直すこと）：
 *   ・冷蔵庫に食材が1つでも入っていれば、献立提案の初期選択は「在庫だけで作る」
 *     （MealWizard の shopMode。在庫0件のときだけ「買い物してもOK」に倒れる）
 *   ・在庫から3案＝/api/research のプロンプト（「3案が全部同じ食材になるのは禁止」）
 *   ・足りない分は packaging.ts の toBuyableFor で「1パック」等の買える単位に変換
 */
export const APP_TAGLINE = "今日なに作るか、家にあるもので決まる。";

