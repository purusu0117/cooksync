// カテゴリ別の既定日数（個別キーワードに当たらなかった場合の保険）
const CATEGORY_DEFAULT: Record<Category, ShelfSpec> = {
  "肉・魚": { sealed: 3 },
  野菜: { sealed: 7 },
  "乳製品・卵": { sealed: 7, opened: 4 },
  主食: { sealed: 30 },
  調味料: { sealed: 365, opened: 60 },
  飲料: { sealed: 90, opened: 5 },
  その他: { sealed: 14 },
};

export interface ShelfGuess {
  days: number;
  /** 個別の食材として辞書に載っていたか（false＝カテゴリ既定＝AIで精度を上げたい） */
  known: boolean;
}

/** 日持ちの目安（日数）と、それが辞書ヒットかどうかを返す */
export function guessShelfLife(
  name: string,
  category?: Category,
  opened = false,
): ShelfGuess {
  const n = normalizeName(name);
  for (const [kws, spec] of NORM_SHELF) {
    if (hits(n, kws)) {
      return { days: opened ? (spec.opened ?? spec.sealed) : spec.sealed, known: true };
    }
  }
  const def = CATEGORY_DEFAULT[category ?? guessCategory(name)];
  return { days: opened ? (def.opened ?? def.sealed) : def.sealed, known: false };
}

/** 日持ちの目安（日数）。従来API互換 */
export function guessShelfLifeDays(
  name: string,
  category?: Category,
  opened = false,
): number {
  return guessShelfLife(name, category, opened).days;
}

export interface Guess {
  category: Category;
  expiresOn: string;
  shelfLifeDays: number;
  /** 辞書に無く、カテゴリ既定でしのいだ＝AI推定を試す価値がある */
  needsAI: boolean;
}

/** 食材名と購入日から、カテゴリと賞味期限の目安を推測する */
export function guessItem(
  name: string,
  purchasedOn: string,
  opened = false,
): Guess {
  const category = guessCategory(name);
  const shelf = guessShelfLife(name, category, opened);
  return {
    category,
    shelfLifeDays: shelf.days,
    needsAI: !shelf.known,
    expiresOn: estimateExpiry(purchasedOn, shelf.days),
  };
}
