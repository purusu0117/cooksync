// キーワードは正規化して比較する。先頭 "=" は完全一致（「水」が「水菜」に当たるのを防ぐ）。
function normKeyword(k: string): string {
  return k.startsWith("=") ? `=${normalizeName(k.slice(1))}` : normalizeName(k);
}
function hits(normalizedName: string, keywords: string[]): boolean {
  return keywords.some((k) =>
    k.startsWith("=") ? normalizedName === k.slice(1) : normalizedName.includes(k),
  );
}

const NORM_CATEGORY: [Category, string[]][] = CATEGORY_KEYWORDS.map(
  ([cat, kws]) => [cat, kws.map(normKeyword)],
);

export function guessCategory(name: string): Category {
  const n = normalizeName(name);
  for (const [cat, kws] of NORM_CATEGORY) {
    if (hits(n, kws)) return cat;
  }
  return "その他";
}

