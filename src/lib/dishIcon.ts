// 主食タグからの補助（料理名で決まらなかったとき）
const STAPLE_FALLBACK: Record<StapleType, DishIconName> = {
  ご飯: "donburi",
  麺: "noodle",
  パン: "bread",
};

/** 料理名（＋主食タグ）から使うイラストを決める */
export function dishIconOf(name: string, staple?: StapleType): DishIconName {
  const n = (name ?? "").replace(/\s|　/g, "");
  for (const [icon, keywords] of RULES) {
    if (keywords.some((k) => n.includes(k))) return icon;
  }
  // 「〜ごはん」で終わる料理はご飯もの（例：やみつき鶏のっけごはん が肉料理になっていた）。
  // チャーハン等は上のRULESで先に拾われるので、ここは取りこぼしの受け皿。
  if (/(のっけ|ごはん|ご飯|めし)$/.test(n)) return "donburi";
  if (staple && STAPLE_FALLBACK[staple]) return STAPLE_FALLBACK[staple];
  return "plate";
}

/** イラストのファイルパス */
export function dishIconSrc(icon: DishIconName): string {
  return `/icons/dish/${icon}.svg`;
}
